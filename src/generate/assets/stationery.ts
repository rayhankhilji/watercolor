/** Color specification sheet (1600 wide) — swatches with every value designers ask for. */
export function paletteSheet(b: ResolvedBrand, c: SocialContext) {
  const names = b.strategy.colorNames ?? {};
  const roles: [string, string][] = [
    ["Primary", b.roles.primary],
    ...b.roles.accent.slice(0, 3).map((a, i) => [`Accent ${i + 1}`, a] as [string, string]),
    ["Ink", b.roles.foreground],
    ["Muted", b.roles.muted],
    ["Background", b.roles.background],
    ["Surface", b.roles.surface],
    ["Border", b.roles.border],
    ["Inverse", b.roles.inverseBackground],
  ];
  const uniq = roles.filter(([, v], i) => roles.findIndex(([, x]) => x === v) === i);
  const sw = uniq
    .map(([label, hex]) => {
      const tc = readableOn(hex, ["#ffffff", "#0a0a0a"]);
      return `<div class="sw"><div class="chip" style="background:${hex};color:${tc}"><span>${esc(names[hex] ?? label)}</span><span class="aa">${contrast(tc, hex) >= 4.5 ? "AA" : ""}</span></div>
      <div class="vals"><b>${esc(label)}</b><span>${hex.toUpperCase()}</span><span>${rgbCss(hex)}</span><span>${oklchCss(hex)}</span></div></div>`;
    })
    .join("");
  const ramps = Object.entries(b.ramps)
    .map(([k, r]) => `<div class="ramp"><div class="rl">${esc(k)}</div>${Object.entries(r.steps).map(([s, v]) => `<div class="st" style="background:${v};color:${readableOn(v, ["#ffffff", "#0a0a0a"])}"><span>${s}${s === r.pinned ? " ●" : ""}</span><span>${v.slice(1).toUpperCase()}</span></div>`).join("")}</div>`)
    .join("");
  return shell(
    c,
    1600,
    "auto",
    `body{background:${b.roles.background};color:${b.roles.foreground};padding:72px}
     h1{${typeStyle(b, "h2", 1)};margin-bottom:8px}.sub{${typeStyle(b, "body", 1.1)};color:${b.roles.muted};margin-bottom:48px}
     .grid{display:grid;grid-template-columns:repeat(5,1fr);gap:20px}
     .chip{height:200px;border-radius:${b.radius.lg}px;padding:18px;display:flex;justify-content:space-between;align-items:flex-end;${typeStyle(b, "label", 1)};box-shadow:inset 0 0 0 1px rgba(0,0,0,.06)}
     .aa{opacity:.7}.vals{display:flex;flex-direction:column;gap:2px;padding:12px 2px;${typeStyle(b, "code", 0.9)};color:${b.roles.muted}}.vals b{font-family:var(--font-body);color:${b.roles.foreground};font-weight:600}
     .ramps{margin-top:40px;display:flex;flex-direction:column;gap:10px}.ramp{display:grid;grid-template-columns:120px repeat(11,1fr);gap:4px;align-items:stretch}
     .rl{${typeStyle(b, "label", 1)};align-self:center;text-transform:capitalize}.st{height:64px;border-radius:6px;padding:8px;display:flex;flex-direction:column;justify-content:space-between;${typeStyle(b, "code", 0.7)}}`,
    `<h1>${esc(b.name)} color</h1><div class="sub">Measured from ${esc(b.domain)} · ramps in OKLCH, brand value pinned (●)</div><div class="grid">${sw}</div><div class="ramps">${ramps}</div>`,
  );
}

