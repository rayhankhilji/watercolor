// Embeds the BrandStrategy interface source into the bundle so `watercolor brief`
// can hand agents the exact schema. Run automatically before builds.
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync(new URL("../src/profile/strategy.ts", import.meta.url), "utf8");
const start = src.indexOf("export type BrandMode");
const end = src.indexOf("export const EMPTY_STRATEGY");
const body = src.slice(start, end).replace(/import[^\n]*\n/g, "").replace(/\bHex\b/g, "string").trim();
writeFileSync(
  new URL("../src/synth/strategy-schema.ts", import.meta.url),
  `// AUTO-GENERATED by scripts/gen-strategy-schema.mjs — do not edit.\nexport const STRATEGY_SCHEMA_TS = ${JSON.stringify(body)};\n`,
);
console.log("strategy schema embedded");
